def main():
    pc.SRC, pc.OUT, pc.PROPOSALS, pc.PARTNER_PAGES = SRC, OUT, PROPOSALS, {}
    pc.CSS = pc.CSS + THEME_CSS
    jobs = []
    for key, d in PROPOSALS.items():
        h = OUT / f"{d['file']}.html"
        h.write_text(pc.proposal_html(key), encoding="utf-8")
        jobs.append([str(h), str(OUT / f"{d['file']}.pdf")])
    env = dict(os.environ)
    if "--pdf" not in sys.argv:
        env["NO_PDF"] = "1"
    with tempfile.NamedTemporaryFile("w", suffix=".js", delete=False) as f:
        f.write(pc.JS)
    try:
        r = subprocess.run(["node", f.name, str(SRC), str(OUT), json.dumps(jobs), json.dumps({})], cwd=ROOT, env=env)
    finally:
        os.unlink(f.name)
    for h, p in jobs:
        print("書きました:", p.replace(".pdf", "-p1.png"), "/ -p2.png" + ("" if env.get("NO_PDF") else " / .pdf"))
    sys.exit(r.returncode)


if __name__ == "__main__":
    main()
