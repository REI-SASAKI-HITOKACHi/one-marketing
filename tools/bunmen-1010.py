#!/usr/bin/env python3
"""LPの文面の小さな直し（依頼 20261008-04-lp）。配信は交通費・浴室の内訳（tools/chuuki-1008.py）と一緒。

  python3 tools/bunmen-1010.py <ページ名> 元.html 出力.html

1. Googleクチコミの件数を書かない（件数は増えて古くなる。LP は23件、実数は25件）。「★5.0」と時点だけ残す
2. 98.6% の脚注の言い回しを、旧アンケートの元の設問と、数えた2つの選択肢に揃える（KYAKUCHU）

旧の見た目・v2 のどちらにも当たるよう、文字列の置き換えで当てる。1つも当たらないページは何もしない。
★公開はまだ。承認まで deploy/netlify には入れない（build-site.py の BUNMEN_PAGES は空）。
"""
import pathlib
import sys

KENSU = [
    ("Googleクチコミ<br>23件<sup>※2</sup>", "Googleクチコミ<sup>※2</sup>"),
    ("Googleの口コミ<br>23件の平均<sup>※2</sup>", "Googleの口コミ<br>平均<sup>※2</sup>"),
    ("※2 Googleクチコミ 23件・平均★5.0（2026年9月時点）", "※2 Googleクチコミの平均★5.0（2026年9月時点）"),
    ("※2 Googleビジネスプロフィールの評価（2026年9月時点・23件）", "※2 Googleビジネスプロフィールの評価（2026年9月時点）"),
    ("（2026年9月時点・23件・平均★5.0／", "（2026年9月時点・平均★5.0／"),
    ("のクチコミは<b>23件・平均★5.0</b>です", "のクチコミは<b>平均★5.0</b>です"),
    ("※2 Googleクチコミの件数と平均は2026年9月時点のものです（23件・平均★5.0）。", "※2 Googleクチコミの平均は2026年9月時点のものです（★5.0）。"),
    ("★5.0Googleクチコミ 23件（2026年9月時点）", "★5.0Googleクチコミ（2026年9月時点）"),
]
# 98.6% の脚注（依頼 20261009-04-lp・20261010-01-lp）。
# 旧アンケート「あなたの声を聴かせてください」の設問「ご家族や知人友人の方へ『オススメしたい』と思いますか？」で、
# 206名＝「すぐにオススメしたい」＋「機会があればススメてもよい」（第6回MTG 6-4 No.8 オーナー決定 10/9）。
# 大きい文字の見出しは、2つの選択肢を両方含む言い方（勧めてもよい）にする。「他の人に勧めたい」は
# 「すぐにオススメしたい」だけに読めるので、機会があればの方まで数えた数字の見出しとしてはずれる。
SETSUMON = "ご利用後アンケートの設問「ご家族や知人友人の方へ『オススメしたい』と思いますか？」"
SENTAKU = "「すぐにオススメしたい」「機会があればススメてもよい」"
KYAKUCHU = [
    # 今の版（aircon・aircon-b・mizumawari・nenmatsu）の見出し
    ("が「他の人に勧めたい」<br>と回答<sup>※1</sup>", "が、ご家族や友人に<br>勧めてもよいと回答<sup>※1</sup>"),
    # 学習版の数字の帯
    ("<span class=\"k\">「他の人に<br>勧めたい」<sup>※1</sup></span>", "<span class=\"k\">ご家族や友人に<br>勧めてもよい<sup>※1</sup></span>"),
    # ※1 の脚注（全LP共通）
    ("※1 「他の人に勧めたい」と回答した割合：集計期間 2023年1月〜2025年12月、回答209名中206名、自社調べ",
     f"※1 {SETSUMON}に、{SENTAKU}と答えた方の割合：集計期間 2023年1月〜2025年12月、回答209名中206名、自社調べ"),
    # ページ下の注記
    ("「98.6%が勧めたい」は自社実施のご利用者アンケートに基づく結果です（実施期間：2023年1月〜2025年12月／回答209名中206名）。",
     f"「98.6%」は、自社実施のご利用者アンケートで、ご家族や知人友人に{SENTAKU}と答えた方の割合です（実施期間：2023年1月〜2025年12月／回答209名中206名）。"),
    # 予約ページ
    ("ご利用後のアンケートで <b>98.6%</b> の方が「他の人にすすめたい」と回答（2023年1月〜2025年12月・209名中206名）",
     f"ご利用後のアンケートで <b>98.6%</b> の方が、ご家族や知人友人に{SENTAKU}と回答（2023年1月〜2025年12月・209名中206名）"),
]


def apply(doc: str, page: str):
    hits = {}
    for a, b in KENSU + KYAKUCHU:
        n = doc.count(a)
        if n:
            doc = doc.replace(a, b)
            hits[a[:16]] = n
    if "勧めたい" in doc or "すすめたい」と回答" in doc:
        raise SystemExit(f"{page}: 98.6% の古い言い回し（勧めたい）が残っています")
    if "23件" in doc:
        raise SystemExit(f"{page}: まだ「23件」が残っています（言い回しが増えた？）")
    return doc, hits


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    page, src, dst = sys.argv[1], pathlib.Path(sys.argv[2]), pathlib.Path(sys.argv[3])
    out, hits = apply(src.read_text(encoding="utf-8"), page)
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(out, encoding="utf-8")
    print(f"{page:13s} " + ("／".join(f"{k}…×{v}" for k, v in hits.items()) or "該当なし"))


if __name__ == "__main__":
    main()
